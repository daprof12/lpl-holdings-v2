export interface AssetData {
  id: string;
  symbol: string;
  name: string;
  category: string;
  exchange: string;
  price: number;
  change24h: number;
  volume: string;
  status: 'active' | 'inactive';
  leverage: {
    basic: number;
    standard: number;
    premium: number;
    silver?: number;
    gold?: number;
    platinum?: number;
  };
}

/**
 * Derives full 5-tier leverage from base 3-tier values.
 * Used to compute silver/gold/platinum when not explicitly set.
 */
export function deriveFullLeverage(leverage: AssetData['leverage']): {
  basic: number;
  standard: number;
  silver: number;
  gold: number;
  platinum: number;
} {
  const { basic, standard, premium } = leverage;
  return {
    basic,
    standard,
    silver: leverage.silver ?? Math.ceil((standard + premium) / 2),
    gold: leverage.gold ?? premium,
    platinum: leverage.platinum ?? (premium === 1 ? 1 : Math.max(premium + 5, Math.round(premium * 1.5))),
  };
}

/**
 * Maps the 5-tier subscription plan to the max leverage for a given asset.
 * 
 * Checks for explicit silver/gold/platinum values first,
 * then falls back to deriving from the 3 base tiers.
 */
export function getMaxLeverageForPlan(
  asset: AssetData | undefined,
  plan: string
): number {
  if (!asset) return 1;
  const { basic, standard, premium } = asset.leverage;

  const fullLeverage = deriveFullLeverage(asset.leverage);

  switch (plan) {
    case 'Basic':
      return basic;
    case 'Standard':
      return standard;
    case 'Silver':
      return fullLeverage.silver;
    case 'Gold':
      return fullLeverage.gold;
    case 'Platinum':
      return fullLeverage.platinum;
    default:
      // Fallback: try lowercase keys for backward compatibility
      if (plan === 'basic') return basic;
      if (plan === 'standard') return standard;
      if (plan === 'premium') return premium;
      return basic;
  }
}

